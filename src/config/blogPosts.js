export function getBlogPost(slug) {
  return BLOG_POSTS.find((post) => post.slug === slug) || null;
}

export function getBlogPostByPath(path) {
  const clean = path && path.length > 1 && path.endsWith('/') ? path.slice(0, -1) : path;
  if (!clean || !clean.startsWith('/blog/')) return null;
  return getBlogPost(clean.slice('/blog/'.length));
}

export function blogPostPath(slug) {
  return `/blog/${slug}`;
}

